"""Two-column template: light sidebar (photo, contact, skills) + main column."""
from __future__ import annotations

from ..latex import escape, escape_url, inline
from .common import BABEL, LABELS
from .common import contacts as _contacts
from .common import strip_scheme as _strip_scheme

NAME = "sidebar"
DESCRIPTION = "Two columns: sidebar (photo, contact, skills) and main column. A4, Lato font."

PREAMBLE = r"""% Generated by CVfacile
\documentclass[<<SIZE>>,a4paper]{extarticle}

\usepackage{iftex}
\ifPDFTeX
  \usepackage[T1]{fontenc}
  \usepackage[utf8]{inputenc}
\fi
\usepackage[default]{lato}
\usepackage[a4paper,margin=0pt]{geometry}
\usepackage{xcolor}
\usepackage{tikz}
\usepackage{fontawesome5}
\usepackage{enumitem}
\usepackage[<<BABEL>>]{babel}
<<BABELSETUP>>
\usepackage[hidelinks]{hyperref}
\usepackage{ragged2e}

\pagestyle{empty}
\setlength{\parindent}{0pt}

\definecolor{accent}{HTML}{<<ACCENT>>}
\definecolor{sidebar}{HTML}{<<SIDEBAR>>}
\definecolor{ink}{HTML}{1F2937}
\definecolor{muted}{HTML}{6B7280}
\color{ink}

\newcommand{\sidesection}[1]{%
  \vspace{9pt}{\color{accent}\bfseries\small\MakeUppercase{#1}}\par
  \vspace{2pt}{\color{accent!40}\rule{\linewidth}{0.6pt}}\par\vspace{3pt}}
\newcommand{\mainsection}[1]{%
  \vspace{8pt}{\color{accent}\bfseries\large\MakeUppercase{#1}}\par
  \vspace{2pt}{\color{accent!40}\rule{\linewidth}{0.6pt}}\par\vspace{4pt}}
\newcommand{\contact}[2]{\makebox[1.2em][c]{\color{accent}#1}\hspace{4pt}{\small #2}\par\vspace{3pt}}
\newcommand{\skillgroup}[2]{%
  {\bfseries\footnotesize #1}\par\vspace{1pt}
  {\footnotesize\color{ink!85} #2}\par\vspace{5pt}}
\newcommand{\job}[4]{%
  {\bfseries\normalsize #1}\hfill{\small\color{muted}#4}\par
  {\color{accent}\bfseries\small #2}{\small\color{muted}\ifx&#3&\else\ \textbullet\ #3\fi}\par\vspace{2pt}}
\newcommand{\project}[4]{%
  {\bfseries\small #1}{\small\color{accent}\ifx&#2&\else\ \textbar\ #2\fi}\par
  {\footnotesize\color{ink!90} #4}\par
  \ifx&#3&\else{\footnotesize\color{muted}\textit{#3}}\par\fi\vspace{5pt}}

\setlist[itemize]{leftmargin=1.1em,itemsep=1.5pt,parsep=0pt,topsep=1pt,label={\color{accent}\textbullet}}

\begin{document}
\begin{tikzpicture}[remember picture,overlay]
  \fill[sidebar] (current page.north west) rectangle ([xshift=6.6cm]current page.south west);
\end{tikzpicture}%
\noindent
"""


def _join(*parts) -> str:
    return r"\ \textbullet\ ".join(escape(p) for p in parts if p)


def render(cv: dict, lang: str, photo_file=None) -> str:
    b = cv.get("basics", {})
    labels = dict(LABELS.get(lang, LABELS["en"]))
    labels.update(cv.get("labels") or {})
    theme = cv.get("theme") or {}

    babel = BABEL.get(lang, "english")
    tex = (PREAMBLE
           .replace("<<SIZE>>", cv.get("_size", "10pt"))
           .replace("<<BABEL>>", babel)
           .replace("<<BABELSETUP>>", r"\frenchsetup{StandardLists=true}" if babel == "french" else "")
           .replace("<<ACCENT>>", str(theme.get("accent", "2F5D8A")).lstrip("#"))
           .replace("<<SIDEBAR>>", str(theme.get("sidebar", "F1F4F8")).lstrip("#")))

    s = []
    # ---------- sidebar ----------
    s.append("\\begin{minipage}[t]{6.6cm}\n\\vspace{0pt}\n\\hspace*{0.75cm}\\begin{minipage}[t]{5.1cm}\n\\vspace{1.1cm}\n")
    if photo_file:
        s.append("\\centering\n\\begin{tikzpicture}\n  \\clip (0,0) circle (1.75cm);\n"
                 "  \\node at (0,-0.3) {\\includegraphics[width=4.8cm]{%s}};\n\\end{tikzpicture}\n"
                 "\\par\\vspace{4pt}\n" % photo_file)
    s.append("\\raggedright\n")

    contacts = _contacts(b)
    if contacts:
        s.append("\\sidesection{%s}\n" % escape(labels["contact"]))
        s.extend("\\contact{%s}{%s}\n" % c for c in contacts)

    if cv.get("languages"):
        s.append("\n\\sidesection{%s}\n" % escape(labels["languages"]))
        rows = []
        for l in cv["languages"]:
            row = "{\\small\\bfseries %s}" % escape(l["language"])
            if l.get("fluency"):
                row += "{\\small\\color{muted} \\ - %s}" % escape(l["fluency"])
            rows.append(row)
        s.append("\\par\\vspace{2pt}\n".join(rows) + "\\par\n")

    if cv.get("skills"):
        s.append("\n\\sidesection{%s}\n" % escape(labels["skills"]))
        for g in cv["skills"]:
            s.append("\\skillgroup{%s}{%s}\n" % (inline(g["name"]), ", ".join(inline(k) for k in g.get("keywords", []))))

    if cv.get("education"):
        s.append("\n\\sidesection{%s}\n" % escape(labels["education"]))
        for i, e in enumerate(cv["education"]):
            if i:
                s.append("\\vspace{5pt}\n")
            s.append("{\\small\\bfseries %s}\\par\n" % inline(e["degree"]))
            if e.get("institution"):
                s.append("{\\footnotesize\\color{accent} %s}\\par\n" % inline(e["institution"]))
            meta = _join(e.get("location"), e.get("dates"))
            if meta:
                s.append("{\\footnotesize\\color{muted} %s}\\par\n" % meta)
    s.append("\\end{minipage}\n\\end{minipage}%\n")

    # ---------- main column ----------
    s.append("\\hspace{0.8cm}%\n\\begin{minipage}[t]{12.9cm}\n\\vspace{1.15cm}\n")
    first, _, last = b.get("name", "").strip().rpartition(" ")
    name = "%s \\textcolor{accent}{%s}" % (escape(first), escape(last)) if first else "\\textcolor{accent}{%s}" % escape(last)
    s.append("{\\fontsize{28}{32}\\selectfont\\bfseries %s}\\par\\vspace{4pt}\n" % name)
    if b.get("label"):
        s.append("{\\Large\\color{muted} %s}\\par\n" % inline(b["label"]))
    s.append("\\vspace{8pt}\n\n")
    if b.get("summary"):
        s.append("\\justifying\\setlength{\\parindent}{0pt}\n\\noindent{\\small %s}\n\\raggedright\n\n" % inline(b["summary"]))

    if cv.get("work"):
        s.append("\\mainsection{%s}\n\n" % escape(labels["work"]))
        for i, w in enumerate(cv["work"]):
            if i:
                s.append("\\vspace{4pt}\n\n")
            s.append("\\job{%s}{%s}{%s}{%s}\n" % (inline(w["position"]), inline(w["company"]),
                                                  escape(w.get("location", "")), escape(w.get("dates", ""))))
            if w.get("highlights"):
                s.append("\\begin{itemize}\n" + "".join("  \\item %s\n" % inline(h) for h in w["highlights"]) + "\\end{itemize}\n")

    if cv.get("projects"):
        s.append("\n\\mainsection{%s}\n" % escape(labels["projects"]))
        for p in cv["projects"]:
            kind = inline(p["kind"]) if p.get("kind") else ""
            if not kind and p.get("url"):
                kind = "\\href{%s}{%s}" % (escape_url(p["url"]), escape(_strip_scheme(p["url"])))
            stack = ", ".join(inline(k) for k in p.get("keywords", []))
            s.append("\\project{%s}{%s}{%s}\n{%s}\n\n" % (inline(p["name"]), kind, stack, inline(p.get("description", ""))))

    s.append("\\end{minipage}\n\n\\end{document}\n")
    return tex + "".join(s)
