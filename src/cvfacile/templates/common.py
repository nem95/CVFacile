"""Shared building blocks for templates.

Content is emitted as calls to a small set of LaTeX macros. Each template
only defines how these macros look and where the sections go:

  \\cvsection{title}
  \\cvjob{position}{company}{location}{dates}   + cvitems environment, \\cvjobsep between jobs
  \\cvproject{name}{kind}{keywords}{description}
  \\cvskill{group}{keywords}                     keywords = \\cvkw{..}\\cvkwsep\\cvkw{..}
  \\cvlang{language}{fluency}                    joined with \\cvlangsep
  \\cvedu{degree}{institution}{location}{dates}
  \\cvcontact{icon}{text}                        joined with \\cvcontactsep
"""
from __future__ import annotations

from ..latex import escape, escape_url, inline

LABELS = {
    "fr": dict(contact="Contact", languages="Langues", skills="Compétences", education="Formation",
               work="Expériences", projects="Projets personnels"),
    "en": dict(contact="Contact", languages="Languages", skills="Skills", education="Education",
               work="Experience", projects="Personal projects"),
    "es": dict(contact="Contacto", languages="Idiomas", skills="Competencias", education="Formación",
               work="Experiencia", projects="Proyectos personales"),
    "de": dict(contact="Kontakt", languages="Sprachen", skills="Kenntnisse", education="Ausbildung",
               work="Berufserfahrung", projects="Persönliche Projekte"),
}
BABEL = {"fr": "french", "en": "english", "es": "spanish", "de": "ngerman",
         "it": "italian", "pt": "portuguese", "nl": "dutch"}

PREAMBLE = r"""% Generated by CVfacile
\documentclass[<<SIZE>>,a4paper]{extarticle}
\usepackage{iftex}
\ifPDFTeX
  \usepackage[T1]{fontenc}
  \usepackage[utf8]{inputenc}
\fi
<<FONTS>>
\usepackage[a4paper,<<GEOMETRY>>]{geometry}
\usepackage{xcolor}
\usepackage{tikz}
\usepackage{fontawesome5}
\usepackage{enumitem}
\usepackage{etoolbox}
\usepackage[<<BABEL>>]{babel}
<<BABELSETUP>>
\usepackage[hidelinks]{hyperref}
\usepackage{ragged2e}

\pagestyle{empty}
\setlength{\parindent}{0pt}
\setlength{\JustifyingParindent}{0pt}
\definecolor{accent}{HTML}{<<ACCENT>>}
\definecolor{soft}{HTML}{<<SOFT>>}
\definecolor{ink}{HTML}{1F2937}
\definecolor{muted}{HTML}{6B7280}
\newcommand{\cvif}[2]{\notblank{#1}{#2}{}}

<<MACROS>>

% Defaults for anything the template did not define
\providecommand{\cvkw}[1]{#1}
\providecommand{\cvkwsep}{, }
\providecommand{\cvlangsep}{\par}
\providecommand{\cvcontactsep}{\par}
\providecommand{\cvjobsep}{\vspace{4pt}}
\ifcsname cvitems\endcsname\else
  \newenvironment{cvitems}{\begin{itemize}[labelsep=0.5em,leftmargin=1.1em,itemsep=1.5pt,parsep=0pt,topsep=1pt,label={\color{accent}\textbullet}]}{\end{itemize}}
\fi
\color{ink}
"""


def strip_scheme(url: str) -> str:
    for prefix in ("https://", "http://", "www."):
        if url.startswith(prefix):
            url = url[len(prefix):]
    return url.rstrip("/")


def contacts(b: dict) -> list:
    """[(icon, latex)] for every contact field present."""
    out = []
    if b.get("email"):
        out.append((r"\faEnvelope", r"\href{mailto:%s}{%s}" % (escape_url(b["email"]), escape(b["email"]))))
    if b.get("phone"):
        out.append((r"\faPhone", escape(b["phone"])))
    if b.get("location"):
        out.append((r"\faMapMarker*", escape(b["location"])))
    for key, icon, host in (("website", r"\faGlobe", None),
                            ("linkedin", r"\faLinkedin", "linkedin.com/in/"),
                            ("github", r"\faGithub", "github.com/")):
        value = b.get(key)
        if not value:
            continue
        # A bare handle ("jdoe") is turned into a profile URL; a domain or URL is kept as given.
        url = value if "://" in value or "." in value.split("/")[0] else "https://" + host + value
        if "://" not in url:
            url = "https://" + url
        out.append((icon, r"\href{%s}{%s}" % (escape_url(url), escape(strip_scheme(url)))))
    return out


class Context:
    """Everything a template needs, already escaped."""

    def __init__(self, cv: dict, lang: str, photo_file=None, accent="2F5D8A", soft="F1F4F8"):
        self.cv, self.lang, self.photo = cv, lang, photo_file
        self.size = cv.get("_size", "10pt")
        b = cv.get("basics", {})
        self.labels = dict(LABELS.get(lang, LABELS["en"]))
        self.labels.update(cv.get("labels") or {})
        theme = cv.get("theme") or {}
        self.accent = str(theme.get("accent", accent)).lstrip("#")
        self.soft = str(theme.get("sidebar", soft)).lstrip("#")
        name = b.get("name", "").strip()
        first, _, last = name.rpartition(" ")
        self.name, self.first, self.last = escape(name), escape(first), escape(last)
        self.label = inline(b["label"]) if b.get("label") else ""
        self.summary = inline(b["summary"]) if b.get("summary") else ""
        self.contact_list = contacts(b)
        self.job_env = None  # optional environment wrapping each job: \begin{env}{dates} ... \end{env}

    def contacts(self) -> str:
        return "\\cvcontactsep\n".join("\\cvcontact{%s}{%s}" % c for c in self.contact_list)

    @staticmethod
    def keywords(items) -> str:
        return "\\cvkwsep ".join("\\cvkw{%s}" % inline(k) for k in items or [])

    def block(self, key: str) -> str:
        cv = self.cv
        items = cv.get(key) or []
        if not items:
            return ""
        out = []
        if key == "work":
            for i, w in enumerate(items):
                if i:
                    out.append("\\cvjobsep\n")
                if self.job_env:
                    out.append("\\begin{%s}{%s}\n" % (self.job_env, escape(w.get("dates", ""))))
                out.append("\\cvjob{%s}{%s}{%s}{%s}\n" % (inline(w["position"]), inline(w["company"]),
                                                          escape(w.get("location", "")), escape(w.get("dates", ""))))
                if w.get("highlights"):
                    out.append("\\begin{cvitems}\n" + "".join("  \\item %s\n" % inline(h) for h in w["highlights"])
                               + "\\end{cvitems}\n")
                if self.job_env:
                    out.append("\\end{%s}\n" % self.job_env)
        elif key == "projects":
            for p in items:
                kind = inline(p["kind"]) if p.get("kind") else ""
                if not kind and p.get("url"):
                    kind = "\\href{%s}{%s}" % (escape_url(p["url"]), escape(strip_scheme(p["url"])))
                out.append("\\cvproject{%s}{%s}{%s}{%s}\n" % (inline(p["name"]), kind, self.keywords(p.get("keywords")),
                                                              inline(p.get("description", ""))))
        elif key == "skills":
            out += ["\\cvskill{%s}{%s}\n" % (inline(g["name"]), self.keywords(g.get("keywords"))) for g in items]
        elif key == "languages":
            out.append("\\cvlangsep\n".join("\\cvlang{%s}{%s}" % (escape(l["language"]), escape(l.get("fluency", "")))
                                           for l in items) + "\n")
        elif key == "education":
            out += ["\\cvedu{%s}{%s}{%s}{%s}\n" % (inline(e["degree"]), inline(e.get("institution", "")),
                                                    escape(e.get("location", "")), escape(e.get("dates", "")))
                    for e in items]
        return "".join(out)

    def section(self, key: str) -> str:
        body = self.block(key)
        return "\\cvsection{%s}\n%s\n" % (escape(self.labels[key]), body) if body else ""

    def sections(self, *keys) -> str:
        return "".join(self.section(k) for k in keys)


def preamble(ctx: Context, fonts: str, geometry: str, macros: str) -> str:
    babel = BABEL.get(ctx.lang, "english")
    return (PREAMBLE
            .replace("<<SIZE>>", ctx.size)
            .replace("<<FONTS>>", fonts)
            .replace("<<GEOMETRY>>", geometry)
            .replace("<<BABEL>>", babel)
            .replace("<<BABELSETUP>>", r"\frenchsetup{StandardLists=true}" if babel == "french" else "")
            .replace("<<ACCENT>>", ctx.accent)
            .replace("<<SOFT>>", ctx.soft)
            .replace("<<MACROS>>", macros.strip()))


def photo_circle(ctx: Context, radius_cm: float, ring: str = "") -> str:
    """Circular photo as a TikZ picture, or '' when there is no photo."""
    if not ctx.photo:
        return ""
    ring_tex = "\\draw[%s] (0,0) circle (%.2fcm);\n" % (ring, radius_cm) if ring else ""
    return ("\\begin{tikzpicture}[baseline=(current bounding box.center)]\n\\begin{scope}\\clip (0,0) circle (%.2fcm);\n"
            "\\node at (0,0) {\\includegraphics[width=%.2fcm]{%s}};\\end{scope}\n%s\\end{tikzpicture}"
            % (radius_cm, radius_cm * 2.4, ctx.photo, ring_tex))


def document(ctx: Context, fonts: str, geometry: str, macros: str, body: str) -> str:
    return preamble(ctx, fonts, geometry, macros) + "\\begin{document}\n" + body + "\n\\end{document}\n"


def paracol(left: str, right: str, ratio: float, sep: str = "0.8cm", rule: str = "") -> str:
    """Two columns that can continue on the next page (paracol package)."""
    rule_tex = "\\setlength{\\columnseprule}{0.6pt}\\colseprulecolor{%s}\n" % rule if rule else ""
    return ("\\columnratio{%.3f}\\setlength{\\columnsep}{%s}\n%s\\begin{paracol}{2}\n%s\n\\switchcolumn\n"
            "\\raggedright\n%s\n\\end{paracol}\n" % (ratio, sep, rule_tex, left, right))


def columns(left: str, right: str, left_width: str, right_width: str, rule: str = "") -> str:
    """Two top-aligned columns, optionally separated by a vertical rule."""
    sep = "\\hfill{\\color{%s}\\vrule width 0.6pt}\\hfill" % rule if rule else "\\hfill"
    return ("\\noindent\\begin{minipage}[t]{%s}\\vspace{0pt}\n%s\\end{minipage}%s"
            "\\begin{minipage}[t]{%s}\\vspace{0pt}\n%s\\end{minipage}\n" % (left_width, left, sep, right_width, right))
